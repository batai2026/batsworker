"""minisign-compatible signing for persona / skill distribution.

Why minisign: the desktop auto-update chain already trusts minisign signatures
(tauri.conf.json pubkey), and the format is the closest thing the ecosystem has
to a lingua franca for "who signed this file" — a signature written here
verifies with the real `minisign` CLI and vice versa (the primary signature;
see the global-signature note under ``sign``).

Trust model (v1) — signed ≠ trusted:
  - Authors sign their bundles with THEIR OWN key.
  - The community catalog pins each entry's public key; installing from the
    catalog verifies against that pinned key (fail closed).
  - Manual installs never refuse: the verification result rides the consent
    summary as a fact (``signed`` / ``key_id`` / ``trusted``), and the user
    decides. Trusted keys are per-user state, added explicitly.

Package layout (what gets signed):
    manifest.sha256           canonical "sha256hex  relpath" lines, LF, sorted
    manifest.sha256.minisig   minisign signature over those exact bytes
Everything else in the bundle directory is covered by the manifest; the
manifest files themselves are excluded (they ARE the statement).

Key files:
  - PUBLIC: byte-identical to a real minisign public key (two lines, base64
    "Ed" + 32-byte public key) — a key generated by real minisign verifies here
    and vice versa.
  - SECRET: our own container ("ow1" KDF tag) — scrypt-derived ChaCha20-Poly1305
    box over the 64-byte seed. Deliberately NOT minisign's encrypted-secret-key
    format (that KDF is libsodium-specific); sign() accepts a password for our
    format, and `verify` never needs the secret. Interop consequence: keys
    generated by the real minisign CLI can be used to VERIFY here (public side)
    but cannot be loaded for signing; keys generated here sign compatibly but
    are not loadable by the real CLI.
"""

from __future__ import annotations

import base64
import hashlib
import os
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Optional

from cryptography.exceptions import InvalidSignature
from cryptography.hazmat.primitives.asymmetric.ed25519 import (
    Ed25519PrivateKey,
    Ed25519PublicKey,
)
from cryptography.hazmat.primitives.ciphers.aead import ChaCha20Poly1305
from cryptography.hazmat.primitives.kdf.scrypt import Scrypt

SIG_ALG = b"Ed"
UNTRUSTED_KEY_COMMENT = "untrusted comment: minisign public key "
UNTRUSTED_SIG_COMMENT = "untrusted comment: signature from "
MANIFEST_NAME = "manifest.sha256"
SIG_SUFFIX = ".minisig"
SIGNED_EXCLUDES = {MANIFEST_NAME, MANIFEST_NAME + SIG_SUFFIX, ".git"}


# -- key files ----------------------------------------------------------------


def _b64(raw: bytes) -> str:
    return base64.b64encode(raw).decode("ascii")


def _unb64(text: str) -> bytes:
    return base64.b64decode(text.strip(), validate=True)


@dataclass
class KeyPair:
    public_key: str  # path to the minisign-format public key file
    secret_key: str  # path to our secret key file
    key_id: str  # 8-byte key id, hex


def generate_keypair(
    dest_dir: str | Path, password: str, *, comment: str = ""
) -> KeyPair:
    """Generate a signing keypair. The public key file is byte-identical to a
    real minisign public key; the secret key uses our own encrypted container."""
    dest = Path(dest_dir)
    dest.mkdir(parents=True, exist_ok=True)
    sk = Ed25519PrivateKey.generate()
    pk_bytes = sk.public_key().public_bytes_raw()
    sk_bytes = sk.private_bytes_raw()

    # minisign key id: the first 8 bytes of sha512(public key), so a real
    # minisign verifier shows the same key id we do.
    key_id = hashlib.sha512(pk_bytes).hexdigest()[:16]
    key_id_bytes = bytes.fromhex(key_id)

    pub_path = dest / f"persona-{key_id}.pub"
    pub_path.write_text(
        f"{UNTRUSTED_KEY_COMMENT}{key_id}\n{_b64(SIG_ALG + pk_bytes)}\n",
        encoding="ascii",
    )

    # Secret container: scrypt(password) -> ChaCha20-Poly1305 box over
    # key_id(8) + sk(32) + pk(32). Salt is random per key; ops/mem are the
    # "interactive" targets minisign uses (2^16 iters, 64 MiB rounded).
    salt = os.urandom(16)
    nonce = os.urandom(12)
    kdf = Scrypt(salt=salt, length=32, n=2**15, r=8, p=1)
    key = kdf.derive(password.encode("utf-8"))
    payload = key_id_bytes + sk_bytes + pk_bytes
    box = ChaCha20Poly1305(key)
    sealed = box.encrypt(nonce, payload, b"ow-persona-signing")

    sk_path = dest / f"persona-{key_id}.sk"
    sk_path.write_text(
        "untrusted comment: ow encrypted secret key (scrypt + chacha20poly1305)\n"
        + _b64(
            b"ow1"
            + salt
            + nonce
            + _u64(2**15)
            + _u64(8 * 1024 * 1024)
            + sealed
        )
        + "\n",
        encoding="ascii",
    )
    return KeyPair(public_key=str(pub_path), secret_key=str(sk_path), key_id=key_id)


def _u64(value: int) -> bytes:
    return value.to_bytes(8, "little")


def _parse_secret(raw: bytes, password: str) -> Ed25519PrivateKey:
    if raw[:3] != b"ow1":
        raise ValueError(
            "unsupported secret key format (real minisign secret keys cannot be "
            "loaded here — sign with a key generated by this tool)"
        )
    salt, nonce = raw[3:19], raw[19:31]
    ops = int.from_bytes(raw[31:39], "little")
    _mem = int.from_bytes(raw[39:47], "little")  # KDF memory hint, unused by r=8,p=1
    sealed = raw[47:]
    kdf = Scrypt(salt=salt, length=32, n=ops, r=8, p=1)
    key = kdf.derive(password.encode("utf-8"))
    payload = ChaCha20Poly1305(key).decrypt(nonce, sealed, b"ow-persona-signing")
    return Ed25519PrivateKey.from_private_bytes(payload[8:40])


def load_public_key(path_or_text: str | Path) -> tuple[str, Ed25519PublicKey]:
    """Read a minisign-format public key file (or raw base64). Returns (key_id, key)."""
    text = Path(path_or_text).read_text(encoding="ascii") if Path(path_or_text).is_file() else str(path_or_text)
    lines = [ln for ln in text.splitlines() if ln.strip()]
    blob = None
    for ln in lines:
        if ln.startswith("untrusted comment:"):
            continue
        blob = _unb64(ln)
        break
    if blob is None or blob[:2] != SIG_ALG or len(blob) != 34:
        raise ValueError("not a minisign public key (expected 'Ed' + 32 bytes)")
    key_id = hashlib.sha512(blob[2:]).hexdigest()[:16]
    return key_id, Ed25519PublicKey.from_public_bytes(blob[2:])


def _sig_key_id(signature_text: str) -> Optional[str]:
    """The key id from the signature's UNTRUSTED comment — a display label only,
    never a trust decision (comment lines are attacker-writable)."""
    for ln in signature_text.splitlines():
        if ln.startswith("untrusted comment: signature from "):
            return ln.rsplit(" ", 1)[-1].strip() or None
    return None


# -- signatures ---------------------------------------------------------------


def sign_bytes(data: bytes, secret_key_path: str | Path, password: str, *, comment: str = "") -> str:
    """Sign bytes; returns the minisign-format signature file text."""
    raw = Path(secret_key_path).read_text(encoding="ascii")
    b64_line = next(
        ln for ln in raw.splitlines() if ln.strip() and not ln.startswith("untrusted comment:")
    )
    sk = _parse_secret(_unb64(b64_line), password)
    pk_bytes = sk.public_key().public_bytes_raw()
    key_id = hashlib.sha512(pk_bytes).hexdigest()[:16]

    sig = sk.sign(data)
    blob = SIG_ALG + sig
    trusted = f"trusted comment: timestamp:{int(time.time())}\t{comment}".encode("utf-8")
    global_sig = sk.sign(blob + trusted)
    return (
        f"{UNTRUSTED_SIG_COMMENT}{key_id}\n"
        f"{_b64(blob)}\n"
        f"{trusted.decode('utf-8')}\n"
        f"{_b64(SIG_ALG + global_sig)}\n"
    )


def verify_bytes(
    data: bytes,
    signature_text: str,
    public_key: str | Path,
) -> dict:
    """Verify minisign signature text over ``data``. Returns a fact, never raises
    for a bad signature: {valid, key_id?, error?}."""
    try:
        key_id, pk = load_public_key(public_key)
        lines = [ln for ln in signature_text.splitlines() if ln.strip()]
        if len(lines) < 2:
            return {"valid": False, "error": "truncated signature file"}
        blob = _unb64(lines[1])
        if blob[:2] != SIG_ALG or len(blob) != 66:
            return {"valid": False, "error": "not an Ed25519 minisign signature"}
        try:
            pk.verify(blob[2:], data)
        except InvalidSignature:
            return {"valid": False, "key_id": key_id, "error": "signature mismatch"}
        return {"valid": True, "key_id": key_id}
    except (ValueError, OSError) as exc:
        return {"valid": False, "error": str(exc)}


# -- bundle (directory) signing ----------------------------------------------

_BUNDLE_SKIP_NAMES = {MANIFEST_NAME, MANIFEST_NAME + SIG_SUFFIX}


def build_manifest(directory: str | Path) -> bytes:
    """Canonical manifest: one 'sha256hex  relpath' line per file (LF, sorted),
    relative POSIX paths, the manifest files themselves excluded."""
    d = Path(directory)
    lines: list[str] = []
    for p in sorted(d.rglob("*")):
        if not p.is_file():
            continue
        rel = p.relative_to(d).as_posix()
        if rel in _BUNDLE_SKIP_NAMES or any(part in SIGNED_EXCLUDES for part in p.parts):
            continue
        lines.append(f"{hashlib.sha256(p.read_bytes()).hexdigest()}  {rel}\n")
    return "".join(lines).encode("utf-8")


def sign_directory(
    directory: str | Path,
    secret_key_path: str | Path,
    password: str,
    *,
    comment: str = "persona bundle",
) -> dict:
    """Write manifest.sha256 + manifest.sha256.minisig into the bundle."""
    d = Path(directory)
    manifest = build_manifest(d)
    (d / MANIFEST_NAME).write_bytes(manifest)
    sig_text = sign_bytes(manifest, secret_key_path, password, comment=comment)
    (d / (MANIFEST_NAME + SIG_SUFFIX)).write_text(sig_text, encoding="ascii")
    # Self-check against the DERIVED public key (never a stored copy — this is
    # the same bytes the user would publish).
    raw = Path(secret_key_path).read_text(encoding="ascii")
    sk = _parse_secret(
        _unb64(next(ln for ln in raw.splitlines() if ln.strip() and not ln.startswith("untrusted comment:"))),
        password,
    )
    pk_bytes = sk.public_key().public_bytes_raw()
    pub_text = (
        f"{UNTRUSTED_KEY_COMMENT}{hashlib.sha512(pk_bytes).hexdigest()[:16]}\n"
        f"{_b64(SIG_ALG + pk_bytes)}\n"
    )
    check = verify_directory(d, public_key=pub_text)
    return {"ok": check["valid"], "files": manifest.decode("utf-8").count("\n"), **check}


def verify_directory(directory: str | Path, *, public_key: Optional[str | Path] = None) -> dict:
    """Verify a bundle's signature. A bundle without a signature is a fact
    ({"signed": False}), not an error — manual installs stay labeled, catalog
    installs fail closed at the caller.

    ``public_key`` set: ``valid`` is the cryptographic verdict against that key
    (and ``pinned`` mirrors it for the catalog path). ``public_key`` omitted:
    the bundle's integrity against its own signed manifest is still checked
    (``files_match``), but ``valid`` is None — cryptographic verification needs
    a key; an untrusted-label key_id comes from the signature's comment line.
    """
    d = Path(directory)
    sig_path = d / (MANIFEST_NAME + SIG_SUFFIX)
    manifest_path = d / MANIFEST_NAME
    if not manifest_path.is_file() or not sig_path.is_file():
        return {"signed": False}
    try:
        expected = build_manifest(d)
        signed = manifest_path.read_bytes()
        files_match = expected == signed
        sig_text = sig_path.read_text(encoding="ascii")
        key_id = _sig_key_id(sig_text)
        out: dict[str, Any] = {
            "signed": True,
            "files_match": files_match,
            "key_id": key_id,
            "valid": None,
        }
        if public_key is not None:
            result = verify_bytes(signed, sig_text, public_key)
            out["valid"] = result.get("valid") is True
            if result.get("error"):
                out["error"] = result["error"]
            out["pinned"] = bool(out["valid"])
        if not files_match:
            out["valid"] = False
            out["error"] = "bundle contents do not match the signed manifest"
        return out
    except (OSError, ValueError) as exc:
        return {"signed": True, "valid": False, "error": str(exc)}


# -- CLI: python -m coworker.personas.signing genkey|sign|verify -----------------


def main() -> None:
    """Author-side signing CLI. Generates keys, signs a bundle directory
    (writing manifest.sha256 + .minisig), and verifies one — the full publish
    step for a community-catalog or hand-shared persona bundle."""
    import argparse

    parser = argparse.ArgumentParser(description="minisign-compatible persona bundle signing")
    sub = parser.add_subparsers(dest="command", required=True)

    g = sub.add_parser("genkey", help="generate a signing keypair")
    g.add_argument("-d", "--dest", required=True, help="output directory")
    g.add_argument("-p", "--password", default="", help="secret-key password (prompt if omitted)")

    s = sub.add_parser("sign", help="sign a persona bundle directory")
    s.add_argument("-d", "--dir", required=True)
    s.add_argument("-S", "--secret-key", required=True)
    s.add_argument("-p", "--password", default="")
    s.add_argument("-c", "--comment", default="persona bundle")

    v = sub.add_parser("verify", help="verify a signed bundle")
    v.add_argument("-d", "--dir", required=True)
    v.add_argument("-P", "--public-key", required=True)

    args = parser.parse_args()
    import getpass

    if args.command == "genkey":
        password = args.password or getpass.getpass("password for the secret key: ")
        pair = generate_keypair(args.dest, password)
        print(f"public key:  {pair.public_key}")
        print(f"secret key:  {pair.secret_key}")
        print(f"key id:      {pair.key_id}")
    elif args.command == "sign":
        password = args.password or getpass.getpass("secret key password: ")
        result = sign_directory(args.dir, args.secret_key, password, comment=args.comment)
        print("signed OK" if result["ok"] else f"SELF-CHECK FAILED: {result}")
        raise SystemExit(0 if result["ok"] else 1)
    elif args.command == "verify":
        result = verify_directory(args.dir, public_key=args.public_key)
        for key, value in result.items():
            print(f"{key}: {value}")
        raise SystemExit(0 if result.get("valid") else 1)


if __name__ == "__main__":
    main()
