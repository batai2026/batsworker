"""Tests for scripts/check_lock_hashes.py (F-c5e5c266 regression guard).

The script's claim is narrow: every distribution line in a requirements-*.lock
must carry at least one --hash=. These tests pin the parser against the actual
shapes uv emits -- marker lines (`pkg==ver ; marker \\`), indented `# via`
notes inside an entry, blank-line separators, and a header comment block at the
top -- plus the two verdicts that must differ (AGENTS §10): a hashed file
passes, a hashless one fails.

We import the script by path (it lives in scripts/, not in the package).
"""

from __future__ import annotations

import importlib.util
from pathlib import Path

import pytest

SCRIPT = Path(__file__).resolve().parents[1] / "scripts" / "check_lock_hashes.py"


def _load():
    spec = importlib.util.spec_from_file_location("check_lock_hashes", SCRIPT)
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(module)
    return module


HASHED = """\
# This file was autogenerated by uv via the following command:
#    uv export --frozen --no-emit-project --format requirements.txt --extra dev -o requirements-dev.lock
aiohappyeyeballs==2.7.1 \\
    --hash=sha256:065665c041c42a5938ed220bdcd7230f22527fbec085e1853d2402c8a3615d9d \\
    --hash=sha256:9243213661e29250eb41368e5daa826fc017156c3b8a11440826b2e3ed376472
    # via aiohttp
aiohttp==3.14.5 \\
    --hash=sha256:0133c3c3b54a0bf1e71fa5c1ad95c93f07fd54e24ef1fe182f5122e1573d2bf1
    # via coworker
websockets==16.1.1 ; python_full_version < '3.11' \\
    --hash=sha256:01fbdcbac298efe19360b94bc0039c8f746f0220ba570f327577bfee81059175
"""

HASHLESS = """\
aiohappyeyeballs==2.7.1
    # via aiohttp
aiohttp==3.14.5
"""

MIXED = """\
aiohappyeyeballs==2.7.1 \\
    --hash=sha256:065665c041c42a5938ed220bdcd7230f22527fbec085e1853d2402c8a3615d9d
    # via aiohttp
aiohttp==3.14.5
"""


@pytest.fixture(scope="module")
def mod():
    return _load()


def test_all_hashed_passes(mod, tmp_path):
    p = tmp_path / "requirements-dev.lock"
    p.write_text(HASHED, encoding="utf-8")
    assert mod.check_file(p) == []


def test_hashless_fails(mod, tmp_path):
    p = tmp_path / "requirements-dev.lock"
    p.write_text(HASHLESS, encoding="utf-8")
    bad = mod.check_file(p)
    assert "aiohappyeyeballs" in bad
    assert "aiohttp" in bad


def test_mixed_reports_only_the_hashless_one(mod, tmp_path):
    p = tmp_path / "requirements-dev.lock"
    p.write_text(MIXED, encoding="utf-8")
    assert mod.check_file(p) == ["aiohttp"]


def test_multiline_continuation_is_one_entry(mod, tmp_path):
    """A hash only on a continuation line still counts for the entry."""
    p = tmp_path / "requirements-dev.lock"
    p.write_text(
        "aiohappyeyeballs==2.7.1 \\\n"
        "    --hash=sha256:abc \\\n"
        "    --hash=sha256:def\n",
        encoding="utf-8",
    )
    assert mod.check_file(p) == []


def test_header_comment_is_not_an_entry(mod, tmp_path):
    p = tmp_path / "requirements-dev.lock"
    p.write_text("# just a comment\n# another\n", encoding="utf-8")
    assert mod.check_file(p) == []


def test_main_via_cli(mod, tmp_path, capsys):
    p = tmp_path / "requirements-dev.lock"
    p.write_text(HASHLESS, encoding="utf-8")
    assert mod.main(["--root", str(tmp_path)]) == 1
    assert "without hashes" in capsys.readouterr().err
