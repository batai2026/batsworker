import type { ApprovalDecision, Item } from "./types";

// Optimistic in-place resolution of the NEWEST unresolved gate of a given kind
// (scans the transcript backwards — a stale gate must not block a newer one).
// These were defined at the bottom of App.tsx and moved here so the responder
// hook (`useGateResponders`) can own the whole gate-answering flow.

export function resolveLastApproval(items: Item[], decision: ApprovalDecision): Item[] {
  const copy = [...items];
  for (let i = copy.length - 1; i >= 0; i--) {
    const it = copy[i];
    if (it.kind === "approval" && !it.resolved) {
      copy[i] = { ...it, resolved: decision };
      break;
    }
  }
  return copy;
}

