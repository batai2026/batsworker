"""Regression tests for scripts/check_lock_consistency.py (F-12b408df).

Covers two layers:

1. normalize_lock() — the comparison core. uv export is *not* byte-stable:
   the same set of hashes can come back in a different row order across runs
   (observed with the 3254-hash dev lock). The check therefore compares
   per-distribution hash *sets*, and these tests pin that behavior down so a
   future "simplification" back to byte-compare gets caught red.

2. main() discriminates — a stale committed lock must make the check fail.
   The subprocess that re-runs `uv export` is monkeypatched so the tests do
   not need a uv binary (CI installs uv itself); what is under test is that
   the *decision* depends on the committed file's content, not on uv.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))

import check_lock_consistency as clc  # noqa: E402

DEV_HEADER = """\
# This file was autogenerated by uv via the following command:
#    uv export --frozen --no-emit-project --format requirements.txt \\
#        --extra dev --extra messaging --extra bedrock -o requirements-dev.lock
#
"""

# Two exports of the same uv.lock, hash rows in different order. Only the
# header `-o` target differs (the check rewrites it to a temp path anyway).
FIRST = DEV_HEADER + """\
aiohttp==3.10.11 \\
    --hash=sha256:aaaa \\
    --hash=sha256:bbbb
    # via openworker
idna==3.7 \\
    --hash=sha256:cccc
    # via yarl
"""

SECOND = DEV_HEADER + """\
aiohttp==3.10.11 \\
    --hash=sha256:bbbb \\
    --hash=sha256:aaaa
    # via openworker
idna==3.7 \\
    --hash=sha256:cccc
    # via yarl
"""

MISSING_HASH = DEV_HEADER + """\
aiohttp==3.10.11 \\
    --hash=sha256:aaaa
    # via openworker
idna==3.7 \\
    --hash=sha256:cccc
    # via yarl
"""

UPGRADED_PKG = DEV_HEADER + """\
aiohttp==3.10.12 \\
    --hash=sha256:aaaa \\
    --hash=sha256:bbbb
    # via openworker
idna==3.7 \\
    --hash=sha256:cccc
    # via yarl
"""


class TestNormalizeLock:
    def test_same_hashes_different_row_order_are_equal(self) -> None:
        assert clc.normalize_lock(FIRST) == clc.normalize_lock(SECOND)

    def test_missing_hash_is_detected(self) -> None:
        assert clc.normalize_lock(FIRST) != clc.normalize_lock(MISSING_HASH)

    def test_upgraded_version_is_detected(self) -> None:
        assert clc.normalize_lock(FIRST) != clc.normalize_lock(UPGRADED_PKG)

    def test_header_comment_not_part_of_spec(self) -> None:
        # Old export used a different -o path in the header; that must not
        # count as a difference (the check rewrites -o to a temp path).
        renamed = SECOND.replace("-o requirements-dev.lock", "-o C:\\temp\\x.lock")
        assert clc.normalize_lock(FIRST) == clc.normalize_lock(renamed)


class TestMainDiscriminates:
    """main() must fail on a stale committed lock (AGENTS rule 2.1/10)."""

    def _make_lock(self, tmp_path: Path, text: str) -> Path:
        (tmp_path / "uv.lock").write_text("# uv.lock stub\n", encoding="utf-8")
        lock = tmp_path / "requirements-dev.lock.new"
        lock.write_text(text, encoding="utf-8")
        renamed = tmp_path / "requirements-dev.lock"
        lock.rename(renamed)
        return renamed

    def _run(self, tmp_path: Path, committed: str, monkeypatch) -> int:
        self._make_lock(tmp_path, committed)
        # Re-run export: emitted text is the up-to-date export (SECOND). The
        # check rewrites the header's -o target to its own temp path, so the
        # fake must write the regenerated text *there*, not a fixed filename.
        def fake_export(argv, cwd, capture_output=True, text=True, encoding="utf-8"):
            out = Path(argv[argv.index("-o") + 1])
            out.write_text(SECOND, encoding="utf-8")
            return clc.subprocess.CompletedProcess(argv, 0, stdout="", stderr="")

        monkeypatch.setattr(clc.subprocess, "run", fake_export)
        return clc.main(["--root", str(tmp_path)])

    def test_consistent_lock_passes(self, tmp_path, monkeypatch) -> None:
        assert self._run(tmp_path, SECOND, monkeypatch) == 0

    def test_stale_lock_fails(self, tmp_path, monkeypatch) -> None:
        # Committed file says aiohttp==3.10.11 with one hash gone:
        # the export (SECOND) disagrees -> exit 1.
        assert self._run(tmp_path, MISSING_HASH, monkeypatch) == 1


class TestExportCommandFromHeader:
    def test_parses_multiline_command(self) -> None:
        lock = Path("requirements-x.lock")
        argv = clc.export_command_from_header(
            _PathLikeHeader(DEV_HEADER, lock)
        )
        assert argv is not None
        assert argv[:3] == ["uv", "export", "--frozen"]


class _PathLikeHeader:
    """Minimal stand-in to keep export_command_from_header testable."""

    def __init__(self, text: str, path: Path) -> None:
        self._text = text
        self._path = path

    def read_text(self, encoding: str = "utf-8") -> str:
        return self._text

    def __str__(self) -> str:
        return str(self._path)
